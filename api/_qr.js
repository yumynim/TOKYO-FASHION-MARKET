// ==========================================================
// 受付コードのQR画像を、メールに直接埋め込める形（base64のPNG）で作る。
// ---------------------------------------------------------
// 以前は api.qrserver.com という無料の外部サービスに都度リクエストして画像を
// 取得していたが、複数人分の受付コードを1通のメールで送ると、メールソフトが
// 複数のQR画像をほぼ同時に取得しようとして2人目以降の画像が表示されない
// 事故が起きうる（姉妹サイトDRESS CODE TOKYOで実際に発生した）。
// 受付コードは当日の入場そのものに関わる最重要の画像なので、
// 外部サービスの都合（速度・障害・同時アクセス制限）に左右されないよう、
// その場でQR画像そのものを生成し、メール本文に直接埋め込む
// （表示時に外部への通信が一切発生しない＝何人分あっても確実に表示される）。
//
// qr-image は依存パッケージを持たない軽量なQR生成ライブラリ。
// サイト内表示（通知のbody_html等）でも使える（CSPの img-src に data: を許可済み）。
// ==========================================================
const qr = require("qr-image");

// size は「1マスあたり何ピクセルで描くか」。実際の画像の一辺は
// おおよそ (QRのマス数 + margin*2) × size ピクセルになる。
// 受付コードの長さでマス数は変わるが、目安として size=20 で一辺500px前後
// （スマホ画面で拡大しても粗くならない解像度）。
function qrDataUri(text, size) {
  const buf = qr.imageSync(String(text), { type: "png", size: size || 20, margin: 2 });
  return `data:image/png;base64,${buf.toString("base64")}`;
}

module.exports = { qrDataUri };
